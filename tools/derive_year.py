#!/usr/bin/env python3
"""Derives a DRAFT year (default 2026) from the previous one inside apps-script/Seed.gs, with deliberate differences so the two years are not identical.
Deterministic (seeded) — re-running gives the same numbers. Scores are INDICATIVE placeholders to be replaced by the real appraisal.
Usage: python3 tools/derive_year.py [--from=2025] [--to=2026]   (run AFTER tools/build_seed.py)"""
import sys, json, random, statistics as st, copy
args=dict(a[2:].split('=') for a in sys.argv[1:] if a.startswith('--'))
SRC,DST=str(args.get('from',2025)),str(args.get('to',2026))
p='apps-script/Seed.gs'; s=open(p,encoding='utf-8').read()
a=s.index('{'); b=s.rindex('}')+1; seed=json.loads(s[a:b])
crit=seed['criteria']; src=seed['years'][SRC]
# ---- criteria changes for DST (total max stays 100: one 5-point item out, one in)
new=[copy.deepcopy(c) for c in crit if c['id']!='C09']                       # "Appearance" dropped
for c in new:
    if c['id']=='C17': c.update(en='Proposes and applies new ideas, tools and automation', ar='يقترح ويطبّق أفكاراً وأدوات وأتمتة جديدة')
new.insert(len(new)-1, {'id':'C20','order':0,'compEn':'Information Security','compAr':'أمن المعلومات',
    'en':'Complies with information security policies and reports incidents promptly','ar':'يلتزم بسياسات أمن المعلومات ويبلّغ عن الحوادث فوراً','max':5,'by':'manager'})
for i,c in enumerate(new,1): c['order']=i
assert sum(c['max'] for c in new)==sum(c['max'] for c in crit)
# ---- team changes: E10 leaves (inactive, no DST scores); two new hires join in Q2
for e in seed['employees']:
    if e['id']=='E10': e['active']=False
for i,n in ((12,'New Staff 1'),(13,'New Staff 2')):
    if not any(e['id']=='E%02d'%i for e in seed['employees']): seed['employees'].append({'id':'E%02d'%i,'name':n,'active':True})
# ---- scores
def mean(v): v=[x for x in v if x is not None]; return sum(v)/len(v) if v else None
idx={c['id']:i for i,c in enumerate(crit)}
DELTA={'E01':0.0,'E02':-0.3,'E03':0.2,'E04':-0.2,'E05':0.5,'E06':-0.4,'E07':0.6,'E08':0.3,'E09':0.4,'E11':-0.3}
DRIFT={'Q1':0.0,'Q2':0.1,'Q3':0.15}
JOIN={'E12':3.4,'E13':3.8}
def clamp(x,lo,hi): return max(lo,min(hi,int(round(x))))
out={}
for q in ('Q1','Q2','Q3'):                                                    # Q4 stays blank (year in progress)
    per={}
    for e in list(DELTA)+list(JOIN):
        if e in JOIN and q=='Q1': continue
        r=random.Random('%s|%s|%s'%(DST,e,q)); row=[]
        if e in DELTA:
            hist={c['id']:mean([src[qq][e][idx[c['id']]] for qq in src if e in src[qq]]) for c in crit}
            own=mean([hist[c['id']] for c in crit if c['id']!='C19'])
        for c in new:
            noise=r.uniform(-0.7,0.7)
            if e in JOIN:
                v=clamp(JOIN[e]+noise+DRIFT[q],1,5) if c['id']!='C19' else clamp(5+r.uniform(-1,1.5),1,10)
            elif c['id']=='C19': v=clamp(hist['C19']+DELTA[e]*2+r.uniform(-1.2,1.2),1,10)
            elif c['id']=='C20': v=clamp(own+DELTA[e]+noise+DRIFT[q],1,5)
            else: v=clamp(hist[c['id']]+DELTA[e]+DRIFT[q]+noise,1,5)
            row.append(v)
        per[e]=row
    out[q]=per
out['Q4']={}
seed.setdefault('criteriaByYear',{})[DST]=new
seed['years'][DST]=out
seed.setdefault('derived',{})[DST]=SRC
open(p,'w',encoding='utf-8').write('/* Generated by tools/build_seed.py + tools/derive_year.py — used once by setup() / apiLoadDraftYear(). */\nconst SEED = '+json.dumps(seed,ensure_ascii=False)+';\n')
for q in ('Q1','Q2','Q3'):
    t=[sum(v) for v in out[q].values()]; print(q,len(out[q]),'emps  avg total',round(sum(t)/len(t),1),'min',min(t),'max',max(t))
