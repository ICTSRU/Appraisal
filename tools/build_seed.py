#!/usr/bin/env python3
"""Builds apps-script/Seed.gs (+ Logos.html) from the original Appraisal_form xlsx files.
Usage: python3 tools/build_seed.py Appraisal_form_2025.xlsx Appraisal_form_2026.xlsx --blank=2026   (--blank=YYYY: load that year's employees/criteria without scores)
Years are read from the sheet names ("Q1 2025" ...). Re-run to regenerate; Seed.gs is only used by setup()."""
import sys, json, re, base64, os, openpyxl
AR = {  # Arabic labels (draft translation — editable in the Criteria tab)
 'Main tasks & responsibilities of the Job':'المهام والمسؤوليات الوظيفية','Productivity':'الإنتاجية',
 'Responsibility and Dependability':'المسؤولية والاعتمادية','Time Management':'إدارة الوقت','Appearance':'المظهر العام',
 'Team spirit':'روح الفريق','CUSTOMER CONSCIOUSNESS':'الوعي بالمستفيد','COMMUNICATION':'التواصل',
 'Results Centered Actions':'الأعمال المرتكزة على النتائج','Performance Management':'إدارة الأداء',
 'Open to change':'الانفتاح على التغيير','CIO':'تقييم الـ CIO',
 'Maintains Knowledge and skills required for successfully carrying out job responsibilities':'يحافظ على المعارف والمهارات اللازمة لأداء المسؤوليات الوظيفية بنجاح',
 'Follows SRU management policies':'يلتزم بسياسات إدارة الجامعة',
 'Maintains a high level of confidentiality regarding student and staff information':'يحافظ على مستوى عالٍ من سرية بيانات الطلاب والموظفين',
 'Meets deadlines':'يلتزم بالمواعيد النهائية','Completes tasks':'ينجز المهام',
 'Requires minimal supervision':'يحتاج إلى حدٍّ أدنى من الإشراف','Responds well to supervision':'يستجيب بشكل جيد للإشراف',
 'Maintains attendance on time':'يلتزم بالحضور في الوقت المحدد','Maintains a distinct appearance':'يحافظ على مظهر لائق ومميز',
 'Contributes to a positive work environment':'يسهم في بيئة عمل إيجابية',
 'Demonstrates ability to interact with customers, both internally and externally':'يُظهر القدرة على التعامل مع المستفيدين داخلياً وخارجياً',
 'Exhibits good verbal and written communication skills as related to job duties':'يتمتع بمهارات تواصل شفهي وكتابي جيدة تتصل بمهام وظيفته',
 'Listens to others':'يُصغي للآخرين',
 'Demonstrates ability to plan and establish priorities to achieve job objectives':'يُظهر القدرة على التخطيط وتحديد الأولويات لتحقيق الأهداف الوظيفية',
 'Demonstrates analytical ability to gather facts and develop solutions. Makes accurate procedures which are sound and timely':'يُظهر قدرة تحليلية على جمع الحقائق وتطوير الحلول، ويتخذ إجراءات دقيقة وسليمة وفي وقتها',
 'Manages workload in an organized manner':'يدير عبء العمل بصورة منظمة','Contributes new ideas and methods.':'يسهم بأفكار وأساليب جديدة',
 'Responds effectively to changing needs of the department':'يستجيب بفاعلية للاحتياجات المتغيرة للإدارة','General evaluation':'التقييم العام'}
def clean(s): return re.sub(r'\s+',' ',str(s)).strip()
BLANK=[int(a.split('=')[1]) for a in sys.argv[1:] if a.startswith('--blank=')]  # years imported WITHOUT scores (employees+criteria only)
files=[a for a in sys.argv[1:] if not a.startswith('--')]; seed={'employees':[],'criteria':[],'years':{}}
for f in files:
    wb=openpyxl.load_workbook(f)
    year=int(re.search(r'(\d{4})',wb.worksheets[0].title).group(1))
    ws=wb.worksheets[0]
    if not seed['employees']:
        for i,c in enumerate(range(6,17),1):
            seed['employees'].append({'id':'E%02d'%i,'name':clean(ws.cell(1,c).value)})
        comp=None
        for i,r in enumerate(range(2,21),1):
            if ws.cell(r,1).value: comp=clean(ws.cell(r,1).value)
            en=clean(ws.cell(r,2).value)
            seed['criteria'].append({'id':'C%02d'%i,'order':i,'compEn':(comp if comp=='CIO' else comp.title()) if comp.isupper() else comp,'compAr':AR[comp],
              'en':en,'ar':AR[en.rstrip('.') if en not in AR else en] if (en in AR or en.rstrip('.') in AR) else '','max':ws.cell(r,5).value,'by':'cio' if comp=='CIO' else 'manager'})
    ys={}
    for q in range(1,5):
        s=wb['Q%d %d'%(q,year)]; per={}
        for i,c in enumerate(range(6,17),1):
            vals=[s.cell(r,c).value for r in range(2,21)]
            if any(v is not None for v in vals): per['E%02d'%i]=vals
        ys['Q%d'%q]={} if year in BLANK else per
    seed['years'][year]=ys
missing=[c['en'] for c in seed['criteria'] if not c['ar']]; assert not missing, missing
with open('apps-script/Seed.gs','w',encoding='utf-8') as o:
    o.write('/* Generated by tools/build_seed.py from the original Appraisal_form workbooks — used once by setup(). */\nconst SEED = '+json.dumps(seed,ensure_ascii=False)+';\n')
L={k:'data:image/png;base64,'+base64.b64encode(open('assets/%s-logo.png'%k,'rb').read()).decode() for k in ('sru','ictd','itoc')}
open('apps-script/Logos.html','w').write('<script>\n/* embedded brand logos (SRU, ICTD, ITOC) — from ICTSRU/brand */\nvar ITOC_LOGOS = '+json.dumps(L)+';\n</script>\n')
print('ok',list(seed['years']),len(seed['employees']),len(seed['criteria']))
